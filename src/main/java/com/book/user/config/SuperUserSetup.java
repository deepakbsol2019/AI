package com.book.user.config;

import com.book.user.service.SuperUserProvisioningService;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.boot.ApplicationArguments;
import org.springframework.boot.ApplicationRunner;
import org.springframework.core.env.Environment;
import org.springframework.stereotype.Component;

/** One explicit operator argument selects the target; no email address is built into the application. */
@Component
public class SuperUserSetup implements ApplicationRunner {
    private static final Logger LOGGER = LoggerFactory.getLogger(SuperUserSetup.class);
    private final Environment environment;
    private final SuperUserProvisioningService provisioning;

    public SuperUserSetup(Environment environment, SuperUserProvisioningService provisioning) {
        this.environment = environment;
        this.provisioning = provisioning;
    }

    @Override
    public void run(ApplicationArguments arguments) {
        String email = environment.getProperty("app.user.super-user.email", "");
        if (email.isBlank()) return;
        String name = environment.getProperty("app.user.super-user.display-name", email);
        var result = provisioning.provision(email, name);
        LOGGER.info(result.changed() ? "SUPER_USER_PROVISIONED" : "SUPER_USER_ALREADY_PROVISIONED");
        if (result.passwordSetupRequired()) {
            LOGGER.warn("SUPER_USER_PASSWORD_SETUP_REQUIRED: Configure SMTP, then use the existing Forgot Password form for the operator-selected email. No email was sent or password/setup token generated by this command.");
        }
    }
}
