package com.classroom.cbsc.service.impl;

import java.util.List;
import java.util.Map;

import org.jspecify.annotations.Nullable;
import org.springframework.ai.chat.client.ChatClient;
import org.springframework.ai.chat.client.advisor.MessageChatMemoryAdvisor;
import org.springframework.ai.chat.memory.ChatMemory;
import org.springframework.ai.chat.memory.ChatMemoryRepository;
import org.springframework.ai.chat.memory.InMemoryChatMemoryRepository;
import org.springframework.ai.chat.memory.MessageWindowChatMemory;
import org.springframework.ai.chat.messages.Message;
import org.springframework.ai.chat.messages.UserMessage;
import org.springframework.ai.chat.prompt.Prompt;
import org.springframework.ai.chat.prompt.SystemPromptTemplate;
import org.springframework.stereotype.Service;

import com.classroom.cbsc.service.TenthClassService;
import com.classroom.response.ResponseModel;
import com.classroom.student.entity.Student;
import com.classroom.student.repo.StudentRepo;
import com.classroom.util.DynamicPromptBuilder;
@Service
public class TenthClassServiceImpl implements TenthClassService {

	private final ChatClient chatClient;
    private final StudentRepo studentRepo;
    private final DynamicPromptBuilder promptBuilder;

    public TenthClassServiceImpl(
            ChatClient chatClient,
            StudentRepo studentRepo,
            DynamicPromptBuilder promptBuilder) {

        this.chatClient = chatClient;
        this.studentRepo = studentRepo;
        this.promptBuilder = promptBuilder;
    }

    @Override
    public ResponseModel getAiResponse(
            Long id,
            String subject,
            String question) {

        // 1. Validate request
        if (id == null) {
            throw new IllegalArgumentException(
                    "Student ID cannot be null");
        }

        if (subject == null || subject.isBlank()) {
            throw new IllegalArgumentException(
                    "Subject cannot be empty");
        }

        if (question == null || question.isBlank()) {
            throw new IllegalArgumentException(
                    "Question cannot be empty");
        }

        // 2. Fetch student
        Student student = studentRepo.findById(id)
                .orElseThrow(() ->
                        new IllegalArgumentException(
                                "Student not found: " + id));

        String studentClass = student.getSclass();

        if (studentClass == null || studentClass.isBlank()) {
            throw new IllegalArgumentException(
                    "Student class cannot be empty");
        }

        String board = student.getBordName();

        if (board == null || board.isBlank()) {
            board = "Unknown";
        }

        // 3. Build class + subject specific prompt
        String instruction =
                promptBuilder.build(studentClass, subject);

        // 4. Create system prompt
        SystemPromptTemplate systemTemplate =
                SystemPromptTemplate.builder()
                        .template(instruction)
                        .build();

        Message systemMessage = systemTemplate.createMessage(
                Map.of(
                        "studentClass", studentClass,
                        "subject", subject,
                        "board", board
                )
        );

        Message userMessage = new UserMessage(question);

        Prompt prompt = new Prompt(
                List.of(systemMessage, userMessage)
        );

        MessageWindowChatMemory messageWindowChatMemory = MessageWindowChatMemory.builder().build();
		MessageChatMemoryAdvisor messageChatMemoryAdvisor = MessageChatMemoryAdvisor.builder(messageWindowChatMemory).build();
		
        ResponseModel response = chatClient.prompt(prompt)
        		.advisors(messageChatMemoryAdvisor)
        		.advisors(e->e.param(ChatMemory.CONVERSATION_ID, student.getId().toString()))
                .call()
                .entity(ResponseModel.class);
		
//		String content = chatClient.prompt(prompt)
//		.advisors(messageChatMemoryAdvisor)
//		.advisors(e->e.param(ChatMemory.CONVERSATION_ID, student.getId().toString()))
//		.call()
//		.content();
//		System.out.println("Final Result ::"+content);
//		ResponseModel response =new ResponseModel();
		
        if (response == null) {
            throw new IllegalStateException(
                    "AI returned an empty response");
        }

        // 6. Set student information
        response.setStudentClass(studentClass);
        response.setSubject(subject);

        // 7. Normalize class for title
        String classLabel =
                normalizeClassLabel(studentClass);

        String title = response.getTitle();

        if (title == null || title.isBlank()) {
            title = subject;
        }

        // Remove class prefix generated by AI
        title = title.replaceFirst(
                "(?i)^Class\\s+[^-:]+\\s*[-:]\\s*",
                ""
        );

        response.setTitle(classLabel + " - " + title);

        // 8. Remove advanced exam information
        // for Classes 1-3
        if (isPrimaryClass(studentClass)) {
            response.setExamTip(null);
            response.setFormulas(List.of());
            response.setSiUnits(List.of());
            response.setConstants(List.of());
        }

        return response;
    }

    private boolean isPrimaryClass(String studentClass) {

        String value = studentClass.trim()
                .toLowerCase(java.util.Locale.ROOT)
                .replaceFirst("^class\\s+", "");

        return switch (value) {
            case "1", "1st", "one", "first",
                 "2", "2nd", "two", "second",
                 "3", "3rd", "three", "third" -> true;
            default -> false;
        };
    }

    private String normalizeClassLabel(String studentClass) {

        String value = studentClass.trim()
                .toLowerCase(java.util.Locale.ROOT)
                .replaceFirst("^class\\s+", "");

        return switch (value) {
            case "one", "first", "1", "1st" -> "Class 1";
            case "two", "second", "2", "2nd" -> "Class 2";
            case "three", "third", "3", "3rd" -> "Class 3";
            case "four", "fourth", "4", "4th" -> "Class 4";
            case "five", "fifth", "5", "5th" -> "Class 5";
            case "six", "sixth", "6", "6th" -> "Class 6";
            case "seven", "seventh", "7", "7th" -> "Class 7";
            case "eight", "eighth", "8", "8th" -> "Class 8";
            case "nine", "ninth", "9", "9th" -> "Class 9";
            case "ten", "tenth", "10", "10th" -> "Class 10";
            case "eleven", "eleventh", "11", "11th" -> "Class 11";
            case "twelve", "twelfth", "12", "12th" -> "Class 12";
            default -> studentClass.trim();
        };
    }
    
}
